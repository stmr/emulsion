use glium::{
	backend::Facade,
	texture::{ClientFormat, MipmapsOption, RawImage2d, SrgbTexture2d},
};
use image::{RgbaImage, error::ImageError};

use std::{
	borrow::Cow,
	cell::{Ref, RefCell},
	ops::Deref,
};

pub struct PictureTextureRef<'a> {
	pic_data: Ref<'a, PictureData>,
}
impl<'a> Deref for PictureTextureRef<'a> {
	type Target = SrgbTexture2d;
	fn deref(&self) -> &SrgbTexture2d {
		if let PictureData::Gpu(texture) = &*self.pic_data { texture } else { unreachable!() }
	}
}

pub enum PictureData {
	EncodedBytes(&'static [u8]),
	Cpu(RgbaImage),
	Gpu(SrgbTexture2d),
}

pub struct PictureMetadata {
	pub width: u32,
	pub height: u32,
}

pub struct Picture {
	data: RefCell<PictureData>,
}

impl Picture {
	pub fn from_encoded_bytes(data: &'static [u8]) -> Picture {
		Picture { data: RefCell::new(PictureData::EncodedBytes(data)) }
	}

	/// This function loads the entire image from file it it hasn't been loaded yet
	pub fn get_metadata(&self) -> Result<PictureMetadata, ImageError> {
		let mut borrowed = self.data.borrow_mut();
		// Decode into a local first so that a failure leaves the picture untouched.
		let rgba = match &*borrowed {
			PictureData::EncodedBytes(bytes) => image::load_from_memory(bytes)?.into_rgba8(),
			PictureData::Cpu(img) => {
				let (width, height) = img.dimensions();
				return Ok(PictureMetadata { width, height });
			}
			PictureData::Gpu(texture) => {
				let (width, height) = texture.dimensions();
				return Ok(PictureMetadata { width, height });
			}
		};
		let (width, height) = rgba.dimensions();
		*borrowed = PictureData::Cpu(rgba);
		Ok(PictureMetadata { width, height })
	}

	pub fn texture<F: Facade>(&self, facade: &F) -> Result<PictureTextureRef<'_>, ImageError> {
		self.upload_to_texture(facade)?;
		if let PictureData::Gpu(_) = &*self.data.borrow() {
			Ok(PictureTextureRef { pic_data: self.data.borrow() })
		} else {
			unreachable!()
		}
	}

	fn upload_to_texture<F: Facade>(&self, facade: &F) -> Result<(), ImageError> {
		let mut borrowed = self.data.borrow_mut();
		// Build the texture from a borrowed/local image first so that a failure
		// leaves the picture untouched.
		let texture = match &*borrowed {
			PictureData::Gpu(_) => return Ok(()),
			PictureData::EncodedBytes(bytes) => {
				Self::cpu_to_texture(&image::load_from_memory(bytes)?.into_rgba8(), facade)?
			}
			PictureData::Cpu(img) => Self::cpu_to_texture(img, facade)?,
		};
		*borrowed = PictureData::Gpu(texture);
		Ok(())
	}

	fn cpu_to_texture<F: Facade>(img: &RgbaImage, facade: &F) -> Result<SrgbTexture2d, ImageError> {
		let (width, height) = img.dimensions();
		let image = RawImage2d {
			data: Cow::Borrowed(img.as_raw().as_slice()),
			width,
			height,
			format: ClientFormat::U8U8U8U8,
		};
		SrgbTexture2d::with_mipmaps(facade, image, MipmapsOption::AutoGeneratedMipmaps)
			.map_err(|e| ImageError::IoError(std::io::Error::other(e)))
	}
}
